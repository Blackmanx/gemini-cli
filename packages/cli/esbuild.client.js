import esbuild from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

mkdirSync('dist/client', { recursive: true });

await esbuild.build({
  entryPoints: ['src/web/client/main.tsx'],
  bundle: true,
  minify: true,
  format: 'esm',
  target: 'es2020',
  jsx: 'automatic',
  outfile: 'dist/client/main.js',
  define: {
    'process.env.NODE_ENV': '"production"',
  },
  // Keep the output self-contained: the bundle is embedded in the CLI as a
  // string, so it must not try to read anything from disk at runtime.
  loader: {
    '.svg': 'dataurl',
    '.png': 'dataurl',
  },
});

// The stylesheet is built on its own and linked from the HTML, so the page
// does not depend on JavaScript to be styled.
await esbuild.build({
  entryPoints: ['src/web/client/styles.css'],
  bundle: true,
  minify: true,
  outfile: 'dist/client/main.css',
});

// Embed the client assets as string constants so the web server can be
// bundled into the CLI without needing readFileSync + __dirname at runtime.
const indexHtml = readFileSync('src/web/client/index.html', 'utf-8');
const clientJs = readFileSync('dist/client/main.js', 'utf-8');
const clientCss = readFileSync('dist/client/main.css', 'utf-8');

writeFileSync(
  'src/web/_client-assets.ts',
  `/**\n * @license\n * Copyright 2026 Google LLC\n * SPDX-License-Identifier: Apache-2.0\n */\n\n// Auto-generated by esbuild.client.js — do not edit\nexport const INDEX_HTML = ${JSON.stringify(indexHtml)};\nexport const CLIENT_JS = ${JSON.stringify(clientJs)};\nexport const CLIENT_CSS = ${JSON.stringify(clientCss)};\n`,
);
