import path from 'node:path';
import { open } from 'node:fs/promises';

/**
 * Refuse edits to files a code generator owns.
 *
 * Ported from omp (`crates/pi-edit/src/path_policy.rs::auto_generated_message`).
 * The agent should change the generator's source or config and re-run it, not
 * hand-edit `foo.pb.go`, or the next regeneration silently reverts the change.
 */

/** Bytes of the file head inspected for a generated-code marker. */
const CHECK_BYTE_COUNT = 1024;
/** Header lines inspected before giving up on finding a marker. */
const HEADER_LINE_LIMIT = 40;

/** Filenames that are generated by construction. */
const GENERATED_FILENAME_PATTERNS = [
  /^zz_generated\./,
  /\.pb\.(go|cc|h|c|js|ts)$/,
  /_pb2\.py$/,
  /_pb2_grpc\.py$/,
  /\.gen\.(go|ts|js|py)$/,
  /\.swagger\.json$/,
  /\.mock\.(go|ts)$/,
  /\.mocks?\.(go|ts|js)$/,
];

/** Generators whose banner is distinctive enough to trust. */
const KNOWN_GENERATORS =
  '(?:protoc(?:-gen-[\\w-]+)?|sqlc|buf|swagger(?:-codegen)?|openapi(?:-generator)?|' +
  'grpc-gateway|mockery|stringer|easyjson|deepcopy-gen|defaulter-gen|conversion-gen|' +
  'client-gen|lister-gen|informer-gen|kysely-codegen|napi-rs)';

const GENERATED_MARKER_PATTERNS = [
  /@generated\b/i,
  /\bcode\s+generated\s+by\s+[a-z0-9_.-]+/i,
  /\bcode\s+generated\b[^\n]*\bdo\s+not\s+edit\b/i,
  /\bthis\s+file\s+was\s+automatically\s+generated\b/i,
  new RegExp(`\\bgenerated\\s+by\\s+${KNOWN_GENERATORS}\\b`, 'i'),
];

const SLASH_EXTENSIONS: Record<string, true> = {
  c: true,
  cc: true,
  cpp: true,
  cs: true,
  dart: true,
  go: true,
  h: true,
  hpp: true,
  java: true,
  js: true,
  jsx: true,
  kt: true,
  kts: true,
  mjs: true,
  cjs: true,
  php: true,
  rs: true,
  scala: true,
  swift: true,
  ts: true,
  tsx: true,
};
const HASH_EXTENSIONS: Record<string, true> = {
  py: true,
  rb: true,
  sh: true,
  bash: true,
  zsh: true,
  yml: true,
  yaml: true,
  toml: true,
  ini: true,
  cfg: true,
  conf: true,
  env: true,
  pl: true,
  r: true,
};
const HTML_EXTENSIONS: Record<string, true> = {
  html: true,
  htm: true,
  xml: true,
  svg: true,
  xhtml: true,
};

type CommentStyle = 'slash' | 'hash' | 'sql' | 'html';

/**
 * Which comment syntaxes a generated-code banner can legally use in this file.
 * An empty result means the language has no banner convention we recognise, so
 * we never guess.
 */
function commentStyles(displayPath: string): CommentStyle[] {
  const name = path.basename(displayPath).toLowerCase();
  if (name === 'dockerfile' || name === 'makefile' || name === 'justfile') {
    return ['hash'];
  }
  const ext = path.extname(name).replace(/^\./, '').toLowerCase();
  if (SLASH_EXTENSIONS[ext]) return ['slash'];
  if (HASH_EXTENSIONS[ext]) return ['hash'];
  if (ext === 'sql') return ['sql'];
  if (HTML_EXTENSIONS[ext]) return ['html'];
  return [];
}

/** The leading comment block of a file, up to the first line of real code. */
function leadingCommentText(content: string, styles: CommentStyle[]): string {
  const result: string[] = [];
  let started = false;
  let slashBlock = false;
  let htmlBlock = false;
  const lines = content.replace(/^\uFEFF/, '').split('\n');
  for (
    let index = 0;
    index < Math.min(lines.length, HEADER_LINE_LIMIT);
    index++
  ) {
    const line = (lines[index] ?? '').trim();
    if (index === 0 && line.startsWith('#!')) continue;
    if (slashBlock) {
      result.push(line);
      slashBlock = !line.includes('*/');
      continue;
    }
    if (htmlBlock) {
      result.push(line);
      htmlBlock = !line.includes('-->');
      continue;
    }
    if (line === '') {
      if (started) result.push('');
      continue;
    }
    const accepted =
      (styles.includes('slash') && line.startsWith('//')) ||
      (styles.includes('hash') && line.startsWith('#')) ||
      (styles.includes('sql') && line.startsWith('--')) ||
      (styles.includes('html') && line.startsWith('<!--')) ||
      (styles.includes('slash') && line.startsWith('/*'));
    if (!accepted) break;
    started = true;
    result.push(line);
    if (styles.includes('slash') && line.startsWith('/*')) {
      slashBlock = !line.includes('*/');
    } else if (styles.includes('html') && line.startsWith('<!--')) {
      htmlBlock = !line.includes('-->');
    }
  }
  return result.join('\n');
}

/** Marker in a generated-code banner, if the header is one. */
export function detectGeneratedMarker(
  content: string,
  displayPath: string,
): string | undefined {
  const styles = commentStyles(displayPath);
  if (styles.length === 0) return undefined;
  const header = leadingCommentText(content, styles);
  for (const pattern of GENERATED_MARKER_PATTERNS) {
    const found = header.match(pattern);
    if (found) return found[0];
  }
  return undefined;
}

/** Marker implied by the filename alone, if the filename gives it away. */
export function detectGeneratedFilename(
  displayPath: string,
): string | undefined {
  const name = path.basename(displayPath);
  return GENERATED_FILENAME_PATTERNS.some((p) => p.test(name))
    ? name
    : undefined;
}

/**
 * The model-facing rejection for a generated file, or `undefined` when the
 * file looks hand-written.
 *
 * `filePath` is read for its first kilobyte; an unreadable file is treated as
 * editable, because failing to read must never block a legitimate write.
 */
export async function autoGeneratedMessage(
  filePath: string,
  displayPath?: string,
): Promise<string | undefined> {
  const display = displayPath ?? filePath;
  const byName = detectGeneratedFilename(display);
  if (byName) return generatedRejection(display, byName);

  let head: Buffer;
  try {
    const handle = await open(filePath, 'r');
    try {
      const buffer = Buffer.alloc(CHECK_BYTE_COUNT);
      const { bytesRead } = await handle.read(buffer, 0, CHECK_BYTE_COUNT, 0);
      head = buffer.subarray(0, bytesRead);
    } finally {
      await handle.close();
    }
  } catch {
    return undefined;
  }
  const marker = detectGeneratedMarker(head.toString('utf8'), display);
  return marker ? generatedRejection(display, marker) : undefined;
}

function generatedRejection(display: string, marker: string): string {
  return (
    `Cannot modify auto-generated file: ${display}\n\n` +
    `This file appears to be automatically generated (detected marker: "${marker}").\n` +
    'Auto-generated files should not be edited directly. Instead:\n' +
    '1. Find the source file or generator configuration\n' +
    '2. Make changes to the source\n' +
    '3. Regenerate the file'
  );
}
